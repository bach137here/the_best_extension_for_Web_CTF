import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const { origin } = JSON.parse(await readFile(new URL('./demo-context.json', import.meta.url)));
const task = await taskSpace('CTF simple verification');
const page = task.page('p1');
await page.goto(origin + '/page/demo');
await page.waitForFunction(() => !!globalThis.CTFPage);
await page.evaluate(async () => { await CTFPageReady; await CTFPage.ready; });
await page.evaluate(() => chrome.storage.local.set({ disabledEndpoints: ['127.0.0.1/page/demo'] }));
await page.waitForFunction(() => globalThis.CTFScope?.disabled && !globalThis.CTFPage && document.querySelector('#password')?.type === 'password');
assert.equal(await page.evaluate(() => document.querySelector('#hidden-token').type), 'hidden');
await page.evaluate(() => chrome.storage.local.set({ disabledEndpoints: [] }));
await page.waitForFunction(() => !globalThis.CTFScope?.disabled && document.querySelector('#password')?.type === 'text');
await page.evaluate(() => chrome.storage.local.set({ disabledEndpoints: ['127.0.0.1/page/paused'] }));
await page.evaluate(() => history.pushState({}, '', '/page/paused?x=1#demo'));
await page.waitForFunction(() => globalThis.CTFScope?.disabled && !globalThis.CTFPage && document.querySelector('#password')?.type === 'password');
await page.goto(origin + '/page/other');
await page.waitForFunction(() => !globalThis.CTFScope?.disabled && document.querySelector('#password')?.type === 'text');
await page.evaluate(() => chrome.storage.local.set({ disabledSites: ['127.0.0.1'] }));
await page.waitForFunction(() => globalThis.CTFScope?.disabled && !globalThis.CTFPage && document.querySelector('#password')?.type === 'password');
await page.evaluate(() => chrome.storage.local.set({ disabledSites: [], disabledEndpoints: [] }));
await page.waitForFunction(() => !globalThis.CTFScope?.disabled && document.querySelector('#password')?.type === 'text');
console.log('PASS: real DOM restores password/hidden fields on disable, resumes helpers, SPA endpoint exclusion and full-host exclusion.');
